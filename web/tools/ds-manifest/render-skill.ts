/**
 * Renders the component section of the design-system skill from the registry.
 * The section sits between SKILL_START and SKILL_END in .agents/skills/design-system/SKILL.md;
 * `bun run ds:manifest` rewrites it and `--check` fails when it is stale.
 */
import type { Manifest } from "../../libs/ui/src/ds-manifest/types";

export const SKILL_START = "<!-- ds-manifest:start -->";
export const SKILL_END = "<!-- ds-manifest:end -->";

const cell = (text: string) =>
  text
    .replace(/\|/g, "\\|")
    .replace(/\n/g, " ")
    .replace(/<[^>`]+>/g, (tag) => `\`${tag}\``);
const code = (text: string) => `\`${text}\``;
const describeReplaced = (replaced: string) =>
  replaced.startsWith("jsx:") || replaced.startsWith("css:")
    ? code(replaced.slice(4))
    : code(replaced.split("/").slice(-2).join("/"));

export function renderSkillSection(manifest: Manifest): string {
  const entries = Object.entries(manifest.components);
  const live = entries.filter(([, c]) => !c.deprecated);
  const deprecated = entries.filter(([, c]) => c.deprecated);
  const tier1 = live.filter(([, c]) => c.tier === 1);
  const tier2 = live.filter(([, c]) => c.tier === 2);
  const gaps = Object.entries(manifest.gaps);

  const lines: string[] = [];
  lines.push(SKILL_START);
  lines.push(
    "<!-- Generated by `bun run ds:manifest` in services/lso/web from libs/ui/src/lib/**/*.manifest.ts. Edit a component's manifest, not this block. -->",
  );
  lines.push("");
  lines.push("### Canonical components (Tier 1)");
  lines.push("");
  lines.push(
    `Import every one of them from ${code(manifest.package)}. Each component folder carries its own manifest; a component not listed here is a Tier 2 pattern, an internal detail, deprecated or a gap.`,
  );
  lines.push("");
  lines.push("| Component | Exports | Use when | Never |");
  lines.push("|---|---|---|---|");
  for (const [name, c] of tier1) {
    lines.push(
      `| ${code(name)} | ${c.exports.map(code).join(", ")} | ${cell(c.use_when)} | ${c.never_when.map(cell).join("; ")} |`,
    );
  }
  lines.push("");
  lines.push("### Decision table: intent → one component");
  lines.push("");
  lines.push(
    "Look the intent up; the answer is the only option. If no row matches, extend `libs/ui` (component + story + manifest in the same folder and PR), never a local copy.",
  );
  lines.push("");
  lines.push("| I need… | Use | Replaces today |");
  lines.push("|---|---|---|");
  const rows: { intent: string; target: string; replaces: string[] }[] = [];
  for (const [name, c] of tier1)
    for (const intent of c.intent) rows.push({ intent, target: code(name), replaces: c.replaces });
  for (const [name, g] of gaps)
    for (const intent of g.intent)
      rows.push({ intent, target: `${code(name)} (gap: add to libs/ui first)`, replaces: g.replaces });
  rows.sort((a, b) => a.intent.localeCompare(b.intent));
  for (const row of rows) {
    const replaced = row.replaces.length ? row.replaces.map(describeReplaced).join(", ") : "—";
    lines.push(`| ${cell(row.intent)} | ${row.target} | ${replaced} |`);
  }
  lines.push("");
  lines.push("### Prop rules");
  lines.push("");
  for (const [name, c] of tier1) {
    if (!c.props_rules?.length) continue;
    lines.push(`- ${code(name)}: ${c.props_rules.map(cell).join("; ")}`);
  }
  lines.push("");
  lines.push("### Patterns (Tier 2, composed from Tier 1)");
  lines.push("");
  for (const [name, c] of tier2) lines.push(`- ${code(name)} (${c.exports.map(code).join(", ")}): ${cell(c.use_when)}`);
  lines.push("");
  lines.push("### Deprecated: never in new code");
  lines.push("");
  for (const [name, c] of deprecated) {
    const d = c.deprecated as NonNullable<typeof c.deprecated>;
    lines.push(`- ${code(name)} → use ${code(d.replaced_by)}. ${cell(d.reason)}`);
  }
  lines.push("");
  lines.push("### Gaps: extend the library, never copy locally");
  lines.push("");
  for (const [name, g] of gaps) {
    lines.push(`- ${code(name)}: ${cell(g.use_when)} Today's copies: ${g.replaces.map(describeReplaced).join(", ")}.`);
  }
  lines.push("");
  lines.push("### Internal exports (do not reach for these)");
  lines.push("");
  for (const [name, reason] of Object.entries(manifest.internal)) lines.push(`- ${code(name)}: ${cell(reason)}`);
  lines.push(SKILL_END);
  return lines.join("\n");
}

export function extractSkillSection(skill: string): string | null {
  const start = skill.indexOf(SKILL_START);
  const end = skill.indexOf(SKILL_END);
  if (start === -1 || end === -1 || end < start) return null;
  return skill.slice(start, end + SKILL_END.length);
}

export function replaceSkillSection(skill: string, section: string): string {
  const current = extractSkillSection(skill);
  if (current === null) throw new Error(`skill is missing the ${SKILL_START} / ${SKILL_END} markers`);
  return skill.replace(current, section);
}
