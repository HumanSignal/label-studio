// Library build of @humansignal/ui for design-sync (claude.ai/design).
//
// The package ships TS source only (package.json main: src/index.ts), so this
// compiles it into a dist the converter can bundle. It reuses the reference
// storybook's own `viteFinal` (aliases, svgr, CSS-module scoped names, the
// lsf- PostCSS prefixing, tailwind) so the compiled class names and CSS are
// identical to what the storybook renders.
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";
import tailwindcss from "tailwindcss";
import { defineConfig, type UserConfig } from "vite";
import sbMain from "../../libs/storybook/.storybook/main";

const here = path.dirname(fileURLToPath(import.meta.url));
const webRoot = path.resolve(here, "../..");
const outDir = path.join(webRoot, "dist/design-sync/ui");
const tailwindConfig = createRequire(import.meta.url)(path.join(webRoot, "tailwind.config.js"));

// Tailwind is JIT: the app's compiled CSS only has the semantic utilities some file already uses (~30 of 176
// semantic colors). The claude.ai/design agent is told to style with the semantic token utilities
// (.design-sync/conventions.md), so compile the whole semantic vocabulary from tokens.js. A strict superset of
// the storybook CSS — no existing class changes.
const SEMANTIC_SAFELIST = [
  {
    pattern: /^(bg|text|border)-(neutral|primary|negative|positive|warning|accent)-(?!.*-raw$).+$/,
    variants: ["hover"],
  },
  {
    pattern:
      /^(p|px|py|pt|pr|pb|pl|m|mx|my|mt|mr|mb|ml|gap|gap-x|gap-y|space-x|space-y)-(tightest|tighter|tight|base|wide|wider|widest)$/,
  },
  { pattern: /^(text|leading)-(body|label|title|headline|display)-(tinier|tiny|smallest|smaller|small|medium|large)$/ },
  { pattern: /^font-(light|regular|medium|semibold|bold|body|headings|mono|base)$/ },
  { pattern: /^rounded(-(t|r|b|l|tl|tr|br|bl))?-(smallest|smaller|small|medium|large|larger|largest)$/ },
  { pattern: /^tracking-(densest|denser|dense|base|wide|wider|widest)$/ },
];

// icons.cjs: generated by gen-icons-entry.mjs (custom Icon* + the Phosphor subset — see that file for why).
export default defineConfig(async () => {
  const base: UserConfig = { mode: "production", plugins: [], resolve: {}, css: {} };
  // biome-ignore lint/suspicious/noExplicitAny: storybook's viteFinal options type isn't needed here
  const cfg = (await sbMain.viteFinal!(base as any, { configType: "PRODUCTION" } as any)) as UserConfig;
  cfg.publicDir = false;
  // biome-ignore lint/suspicious/noExplicitAny: postcss plugin objects
  const plugins = (cfg.css?.postcss as any)?.plugins as any[];
  const twIndex = plugins.findIndex((p) => p?.postcssPlugin === "tailwindcss");
  if (twIndex < 0) throw new Error("tailwindcss postcss plugin not found in the storybook viteFinal config");
  plugins[twIndex] = tailwindcss({ config: { ...tailwindConfig, safelist: SEMANTIC_SAFELIST } });
  cfg.build = {
    ...cfg.build,
    outDir,
    emptyOutDir: true,
    minify: true,
    sourcemap: false,
    cssCodeSplit: false,
    // Library mode inlines assets as data URIs regardless (Figtree ships inside style.css).
    assetsInlineLimit: 0,
    lib: {
      entry: { index: path.join(here, "ds-entry.ts"), icons: path.join(webRoot, ".design-sync/.cache/icons-entry.ts") },
      // CJS, not ES: bundled CommonJS deps keep real `require("react")` calls the converter can
      // map to window.React (rolldown's ESM output turns them into a throwing __require shim).
      formats: ["cjs"],
      fileName: (_format, name) => `${name}.cjs`,
      cssFileName: "style",
    },
    rollupOptions: {
      // React stays external: the converter maps it to the page's window.React.
      external: [/^react(\/.*)?$/, /^react-dom(\/.*)?$/, /^react-is$/, /^scheduler(\/.*)?$/],
    },
  };
  return cfg;
});
