// Generates .design-sync/.cache/icons-entry.ts — the @humansignal/icons surface shipped to claude.ai/design.
//
// @humansignal/icons re-exports ALL of @phosphor-icons/react (~1500 icons x 6 weights, ~5 MB), which pushes the
// bundle past what one upload accepts. Instead ship:
//   - every custom Icon* svg from libs/ui/src/assets/icons/index.ts (minus its `export * from "./icons"`),
//   - the Phosphor names the LSO + LSE apps/libs actually import (scanned fresh on every build),
//   - plus phosphor-extras.txt — common UI icons worth offering the design agent even if unused today.
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const webRoot = path.resolve(here, "../..");
const iconsDir = path.join(webRoot, "libs/ui/src/assets/icons");
const out = path.join(webRoot, ".design-sync/.cache/icons-entry.ts");

const phosphor = new Set(Object.keys(await import("@phosphor-icons/react")));

const roots = ["apps", "libs", "../../lse/web/apps", "../../lse/web/libs"]
  .map((r) => path.join(webRoot, r))
  .filter(existsSync);
const SKIP = new Set(["node_modules", "dist", ".design-sync", "coverage", "storybook-static"]);
const importRx = /import\s*(?:type\s*)?\{([^}]*)\}\s*from\s*["'](?:@humansignal\/icons|@phosphor-icons\/react)["']/g;
const used = new Set();
function walk(dir) {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    if (e.isDirectory()) {
      if (!SKIP.has(e.name) && !e.name.startsWith(".")) walk(path.join(dir, e.name));
    } else if (/\.[jt]sx?$/.test(e.name) && !/\.(test|spec)\.[jt]sx?$/.test(e.name)) {
      for (const m of readFileSync(path.join(dir, e.name), "utf8").matchAll(importRx)) {
        for (const part of m[1].split(",")) {
          const name = part
            .trim()
            .replace(/^type\s+/, "")
            .split(/\s+as\s+/)[0]
            .trim();
          if (name && phosphor.has(name)) used.add(name);
        }
      }
    }
  }
}
for (const r of roots) walk(r);

const extras = readFileSync(path.join(here, "phosphor-extras.txt"), "utf8")
  .split("\n")
  .map((l) => l.replace(/#.*/, "").trim())
  .filter(Boolean);
for (const n of extras) {
  if (!phosphor.has(n)) throw new Error(`phosphor-extras.txt: ${n} is not a @phosphor-icons/react export`);
}
const phosphorNames = [...new Set([...used, ...extras, "IconContext", "IconBase"])].sort();

const rel = path.relative(path.dirname(out), iconsDir).split(path.sep).join("/");
const custom = readFileSync(path.join(iconsDir, "index.ts"), "utf8")
  .split("\n")
  .filter((l) => /^export \{ ReactComponent as \w+ \} from "\.\/[^"]+\.svg";$/.test(l))
  .map((l) => l.replace('from "./', `from "${rel}/`));

mkdirSync(path.dirname(out), { recursive: true });
writeFileSync(
  out,
  `// GENERATED by .design-sync/build/gen-icons-entry.mjs — do not edit.\n${custom.join("\n")}\nexport {\n${phosphorNames
    .map((n) => `  ${n},`)
    .join("\n")}\n} from "@phosphor-icons/react";\n`,
);
console.error(
  `icons entry: ${custom.length} custom Icon* + ${phosphorNames.length} Phosphor (${used.size} used in apps/libs, ${extras.length} extras)`,
);
